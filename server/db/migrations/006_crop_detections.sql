CREATE TABLE IF NOT EXISTS crop_detections (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  farmer_id BIGINT UNSIGNED NOT NULL,
  land_id BIGINT UNSIGNED NULL,
  image_file VARCHAR(500) NOT NULL,
  image_mime_type VARCHAR(100) NOT NULL,
  crop_name VARCHAR(150) NOT NULL DEFAULT 'Unknown Crop',
  scientific_name VARCHAR(200) NULL,
  detected_crops JSON NULL,
  confidence DECIMAL(5,4) NULL,
  bounding_boxes JSON NULL,
  growth_stage VARCHAR(100) NULL,
  health_status VARCHAR(100) NULL,
  possible_issues JSON NULL,
  recommendations JSON NULL,
  analysis_json JSON NULL,
  model_name VARCHAR(150) NULL,
  model_version VARCHAR(150) NULL,
  validation_status VARCHAR(80) NOT NULL DEFAULT 'not_validated',
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (farmer_id) REFERENCES farmer_profiles(id) ON DELETE CASCADE,
  FOREIGN KEY (land_id) REFERENCES lands(id) ON DELETE SET NULL,
  INDEX idx_crop_detections_farmer_created (farmer_id, created_at),
  INDEX idx_crop_detections_land_created (land_id, created_at),
  INDEX idx_crop_detections_crop_name (crop_name)
);
